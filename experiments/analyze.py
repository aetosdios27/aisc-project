"""Paired uncertainty and consistency audit, derived only from saved transcripts."""
import json
import random
from collections import defaultdict
from pathlib import Path
from statistics import mean
from engine.board import Board
from experiments.tournament import digest, summarize


def score(game, name):
    return 0.5 if game['winner'] == 0 else float(game['winner'] == (1 if game['black'] == name else -1))


def paired_intervals(games, samples=2000, seed=1911):
    pairs = defaultdict(list)
    for game in games:
        pairs[tuple(sorted((game['black'], game['white'])))].append(game)
    rows = []
    for names, group in sorted(pairs.items()):
        blocks = defaultdict(list)
        for game in group:
            blocks[game['opening_seed']].append(game)
        for block in blocks.values():
            if len(block) != 2 or block[0]['initial'] != block[1]['initial'] or block[0]['black'] == block[1]['black']:
                raise ValueError('Expected complete swapped-color opening pairs')
        rates = [mean(score(g, names[0]) for g in block) for block in blocks.values()]
        rng = random.Random(seed)
        bootstrap = sorted(mean(rng.choice(rates) for _ in rates) for _ in range(samples))
        rows.append({'first': names[0], 'second': names[1], 'games': len(group), 'opening_pairs': len(blocks),
                     'unique_openings': len({g['initial'] for g in group}), 'first_score_rate': mean(rates),
                     'first_score_interval95': [bootstrap[int(samples * 0.025)], bootstrap[int(samples * 0.975) - 1]],
                     'bootstrap_samples': samples, 'bootstrap_seed': seed})
    return rows


def audit_games(result):
    corrected = False
    for game in result['games']:
        board = Board.initial()
        for move in game['opening_moves']:
            board = board.play(move)
        if board.serialize() != game['initial']:
            raise ValueError('Opening does not reconstruct initial board')
        for turn in game['turns']:
            if turn['player'] != board.turn:
                raise ValueError('Transcript perspective mismatch')
            board = board.play(turn['move'])
        if board.serialize() != game['final'] or board.winner() != game['winner']:
            raise ValueError('Transcript does not reconstruct final state')
        if 'continuation_length' not in game:
            game['continuation_length'] = game['game_length']
            game['game_length'] += sum(m is not None for m in game['opening_moves'])
            corrected = True
        if game['game_length'] != 60 - board.cells.count(0):
            raise ValueError('Incorrect full game placement count')
    if corrected:
        result['derived_metrics'] = {'change': 'Include seeded opening placements in game_length; preserve original continuation_length',
                                     'analysis_sha256': digest(__file__)}
        result['summary'] = summarize(result['games'], list(result['summary']))
    return corrected


def analyze():
    from experiments.tournament import save_results
    root = Path('experiments/results')
    path = root / 'tournament.json'
    result = json.loads(path.read_text())
    if audit_games(result):
        save_results(result, path)
    depth = json.loads((root / 'depth.json').read_text())
    for study in depth['studies']:
        audit_games(study)
    (root / 'depth.json').write_text(json.dumps(depth, indent=2))
    intervals = paired_intervals(result['games'])
    analysis = {'status': 'pilot', 'tournament_sha256': digest(path),
                'analysis_sha256': digest(__file__), 'replayed_games': len(result['games']) + sum(len(s['games']) for s in depth['studies']),
                'pairings': intervals,
                'interpretation': 'Percentile intervals resample opening pairs. Small deterministic panels are preliminary.'}
    (root / 'analysis.json').write_text(json.dumps(analysis, indent=2))
    write_report(result, analysis)
    for row in intervals:
        if row['first'] in ('manual-ab', 'ga-ab', 'neural-ab') and row['second'] in ('manual-ab', 'ga-ab', 'neural-ab'):
            print(json.dumps(row))
    return analysis


def write_report(tournament, analysis):
    root = Path('experiments/results')
    benchmark = json.loads((root / 'benchmark.json').read_text())
    rows = [r for r in benchmark['rows'] if r['depth'] == 3 and r['ordering'] == 'position']
    mm, ab = sum(r['minimax_nodes'] for r in rows), sum(r['alphabeta_nodes'] for r in rows)
    neural = json.loads((root / 'neural.json').read_text())
    ga = json.loads((root / 'ga.json').read_text())
    text = ['# Measured pilot results', '',
            'Generated by `python -m experiments.analyze` from saved JSON. These are preliminary measurements, not a final superiority claim.', '',
            f"The round robin contains {len(tournament['games'])} games, {tournament['config']['games_per_pair']} per opponent pair, at placement depth {tournament['config']['depth']}. The primary evaluator pairings each contain ten distinct seeded openings played with both colors. All {analysis['replayed_games']} main/depth-study transcripts replay to their recorded final states.", '',
            '## Search correctness and efficiency', '',
            f'Across six seeded depth-three positions with positional ordering, Minimax visits {mm:,} nodes and Alpha-Beta visits {ab:,}: {100*(mm-ab)/mm:.1f}% fewer. Every measured position/depth/ordering combination asserts identical value and selected move.', '',
            '## Direct evaluator comparisons', '',
            '| First engine | Opponent | First engine score rate | Paired bootstrap 95% interval |',
            '| --- | --- | --- | --- |']
    for row in analysis['pairings']:
        if row['first'] in ('manual-ab', 'ga-ab', 'neural-ab') and row['second'] in ('manual-ab', 'ga-ab', 'neural-ab'):
            lo, hi = row['first_score_interval95']
            text.append(f"| {row['first']} | {row['second']} | {100*row['first_score_rate']:.1f}% | {100*lo:.1f}–{100*hi:.1f}% |")
    text.extend(['', 'Score rate counts a draw as half. Intervals resample whole opening pairs 2,000 times. The small opening panel limits interpretation. The GA has no demonstrated gain over manual evaluation in this pilot; both manual and GA perform better than this initial neural model on the measured panel.', '',
                 '## Evolution and neural training', '',
                 f"The GA runs {ga['config']['generations']} generations with population {ga['config']['population']}. Its selected champion scores {ga['validation_score']:.2f} on the small fixed validation panel. Training fitness uses a changing opponent panel and is not a comparable cross-generation strength estimate.", '',
                 f"The neural model has {neural['config']['parameters']:,} parameters. Validation selects epoch {neural['best_epoch']} of {neural['config']['epochs']}. Test MSE is {neural['test']['mse']:.4f}, versus {neural['test_mean_baseline_mse']:.4f} for the training-mean predictor; MAE is {neural['test']['mae']:.4f} and Pearson correlation is {neural['test']['correlation']:.4f}. Training loss continues falling while validation loss worsens: clear overfitting. A prediction improvement does not imply playing-strength improvement.", '',
                 '## Next research gate', '',
                 'Keep the mandatory system stable by 20 October. On 21–24 October, use the frozen protocol for more independent opening pairs and training/evolution seeds, uncertainty analysis, the report, slides and viva. Do not tune against final test games. See `experiments.md` for the prespecified comparison controls.', ''])
    Path('docs/results.md').write_text('\n'.join(text))


if __name__ == '__main__':
    analyze()
